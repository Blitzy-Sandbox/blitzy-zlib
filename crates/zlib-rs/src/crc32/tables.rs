    /// Widen a 32-bit CRC residue to a [`Word`], mirroring the implicit
    /// widening of `crc32.c`'s `byte_swap(z_word_t)` argument.
    #[cfg(target_pointer_width = "64")]
    fn widen(residue: u32) -> Word {
        Word::from(residue)
    }

    /// Widen a 32-bit CRC residue to a [`Word`]. The identity when [`Word`] is
    /// itself 32 bits wide.
    #[cfg(not(target_pointer_width = "64"))]
    fn widen(residue: u32) -> Word {
        residue
    }

    /// Mirrors `multmodp` (`crc32.c` L163-L178): return `a(x) * b(x) mod p(x)`
    /// over `GF(2)`, with the polynomials reflected.
    ///
    /// Test-only. The shipped code performs no modular arithmetic at all,
    /// because every table in this module is compile-time data. This exists so
    /// the transcription can be re-derived from `crc32.c`'s own algorithm
    /// rather than merely compared against a copy of its output.
    fn multmodp(a: u32, mut b: u32) -> u32 {
        let mut m: u32 = 1 << 31;
        let mut p: u32 = 0;
        loop {
            if a & m != 0 {
                p ^= b;
                if a & (m - 1) == 0 {
                    break;
                }
            }
            if m == 1 {
                // Reachable only for `a == 0`, which `crc32.c` L160-L162
                // documents as outside the contract. Breaking here keeps the
                // helper total instead of spinning.
                break;
            }
            m >>= 1;
            b = if b & 1 != 0 { (b >> 1) ^ POLY } else { b >> 1 };
        }
        p
    }

    /// Mirrors `x2nmodp` (`crc32.c` L184-L195): return `x^(n * 2^k) mod p(x)`,
    /// reading the powers of `x` out of [`X2N_TABLE`].
    ///
    /// This reads the transcribed table, exactly as the C does, so
    /// `x2n_table_matches_make_crc_table` below establishes that table from
    /// [`POLY`] alone first, and `braid_rows_are_zero_extended_byte_crcs`
    /// re-checks the braid tables against [`CRC_TABLE`] without this helper.
    fn x2nmodp(mut n: usize, mut k: usize) -> u32 {
        let mut p: u32 = 1 << 31; // x^0 == 1, reflected
        while n != 0 {
            if n & 1 != 0 {
                // `k & 31` is always a valid index into a 32-entry table;
                // `unwrap_or` states that without relying on a panic path.
                let factor = X2N_TABLE.get(k & 31).copied().unwrap_or(0);
                p = multmodp(factor, p);
            }
            n >>= 1;
            k += 1;
        }
        p
    }

    /// One byte-wise CRC step driven purely by [`CRC_TABLE`]:
    /// `crc = (crc >> 8) ^ crc_table[(crc ^ byte) & 0xff]`.
    fn table_step(crc: u32, byte: u8) -> u32 {
        // The low byte of `crc`, obtained without a truncating cast.
        let low = u8::try_from(crc & 0xff).unwrap_or(0);
        let entry = CRC_TABLE.get(usize::from(low ^ byte)).copied().unwrap_or(0);
        (crc >> 8) ^ entry
    }

    /// Byte-wise CRC-32 of `data`, seeded with `init`, driven purely by
    /// [`CRC_TABLE`].
    fn bytewise(data: &[u8], init: u32) -> u32 {
        data.iter().fold(init, |crc, &byte| table_step(crc, byte))
    }

    /// Byte-wise CRC-32, zero-seeded, of the single byte `byte` followed by
    /// `zeros` zero bytes. Driven purely by [`CRC_TABLE`].
    fn byte_then_zeros(byte: u8, zeros: usize) -> u32 {
        (0..zeros).fold(table_step(0, byte), |crc, _| table_step(crc, 0))
    }

    /// Regenerate the byte-wise table exactly as `make_crc_table` does at
    /// `crc32.c` L248-L256.
    fn regenerate_crc_table() -> [u32; 256] {
        let mut table = [0u32; 256];
        for (slot, index) in table.iter_mut().zip(0u32..) {
            let mut p = index;
            for _ in 0..8 {
                p = if p & 1 != 0 { (p >> 1) ^ POLY } else { p >> 1 };
            }
            *slot = p;
        }
        table
    }

    /// Regenerate the powers-of-`x` table exactly as `make_crc_table` does at
    /// `crc32.c` L259-L262: seed with the reflected `x^1`, then square.
    fn regenerate_x2n_table() -> [u32; 32] {
        let mut table = [0u32; 32];
        let mut p: u32 = 1 << 30; // x^1, reflected
        for (index, slot) in table.iter_mut().enumerate() {
            if index != 0 {
                p = multmodp(p, p);
            }
            *slot = p;
        }
        table
    }

    /// Regenerate both braid tables exactly as `braid()` does at `crc32.c`
    /// L461-L473, for the active [`N`] and [`W`].
    fn regenerate_braid_tables() -> ([[u32; 256]; W], [[Word; 256]; W]) {
        let mut little = [[0u32; 256]; W];
        for (k, row) in little.iter_mut().enumerate() {
            // `p = x2nmodp((n * w + 3 - k) << 3, 0)`, then `ltl[k][0] = 0` and
            // `ltl[k][i] = multmodp(i << 24, p)` for the remaining 255 entries.
            let p = x2nmodp((N * W + 3 - k) << 3, 0);
            for (slot, index) in row.iter_mut().zip(0u32..) {
                *slot = if index == 0 {
                    0
                } else {
                    multmodp(index << 24, p)
                };
            }
        }

        // `big[w - 1 - k][i] = byte_swap(q)` for the same `q` written to
        // `ltl[k][i]`, so the rows pair up in reverse.
        let mut big: [[Word; 256]; W] = [[0; 256]; W];
        for (big_row, little_row) in big.iter_mut().zip(little.iter().rev()) {
            for (slot, &residue) in big_row.iter_mut().zip(little_row.iter()) {
                *slot = widen(residue).swap_bytes();
            }
        }

        (little, big)
    }

