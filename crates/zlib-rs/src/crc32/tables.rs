    #[test]
    fn braid_tables_are_byte_swapped_row_reversed_images() {
        // crc32.c L466-L470: ltl[k][0] = 0, big[w - 1 - k][0] = 0, and
        // big[w - 1 - k][i] = byte_swap(ltl[k][i]). This one identity validates
        // the whole big table against the little one; a failure here means the
        // rows were transposed, or slices from different N or W blocks of
        // crc32.h were mixed.
        let pairs = CRC_BRAID_TABLE.iter().zip(CRC_BRAID_BIG_TABLE.iter().rev());
        for (k, (little_row, big_row)) in pairs.enumerate() {
            assert_eq!(little_row[0], 0, "crc_braid_table[{k}][0]");
            assert_eq!(big_row[0], 0, "crc_braid_big_table[{}][0]", W - 1 - k);
            for (i, (&residue, &big)) in little_row.iter().zip(big_row.iter()).enumerate() {
                assert_eq!(
                    big,
                    widen(residue).swap_bytes(),
                    "crc_braid_big_table[{}][{i}] vs crc_braid_table[{k}][{i}]",
                    W - 1 - k
                );
            }
        }
    }

