    #[test]
    fn braid_rows_are_zero_extended_byte_crcs() {
        // Independent of multmodp and x2nmodp: row k, entry i is the zero-seeded
        // byte-wise CRC of the single byte i followed by N * W - 1 - k zero
        // bytes, which is precisely the shift x2nmodp((N * W + 3 - k) << 3, 0)
        // applies. Driven only by CRC_TABLE, so it cannot share a bug with the
        // modular-arithmetic helpers above.
        for (k, row) in CRC_BRAID_TABLE.iter().enumerate() {
            let zeros = N * W - 1 - k;
            for (i, &expected) in row.iter().enumerate() {
                // `i` spans 0..256, so the mask is a no-op that also proves the
                // conversion cannot fail.
                let byte = u8::try_from(i & 0xff).unwrap_or(0);
                assert_eq!(
                    byte_then_zeros(byte, zeros),
                    expected,
                    "crc_braid_table[{k}][{i}]"
                );
            }
        }
    }

    #[test]
    fn byte_wise_table_reproduces_the_standard_check_value() {
        // The CRC-32 catalogue "check" value: the CRC of the nine ASCII bytes
        // "123456789", with the usual all-ones seed and final complement, is
        // 0xcbf43926. This ties CRC_TABLE to the wire format rather than only to
        // crc32.c's generator.
        assert_eq!(
            bytewise(b"123456789", 0xffff_ffff) ^ 0xffff_ffff,
            0xcbf4_3926
        );
        // The empty message leaves the seed untouched, so its CRC is zero.
        assert_eq!(bytewise(b"", 0xffff_ffff) ^ 0xffff_ffff, 0x0000_0000);
    }
