/// Run-length encoding compression (Z_RLE strategy).
///
/// Simply looks for runs of bytes, generating matches only of distance one.
/// Does not maintain a hash table. (It will be regenerated if this run of
/// deflate switches away from Z_RLE.)
///
/// # Algorithm
///
/// For each position in the input:
///
/// 1. Check if the byte at `window[strstart]` equals the byte at
///    `window[strstart - 1]` (distance 1). If so, scan forward to
///    measure the run length (up to [`MAX_MATCH`] = 258 bytes).
/// 2. If the run length ≥ [`MIN_MATCH`] (3), emit a distance/length
///    pair via [`tally_dist`] with distance = 1.
/// 3. Otherwise, emit a literal byte via [`tally_lit`].
/// 4. When the symbol buffer is full (tally returns `true`), flush
///    the current block.
///
/// # Parameters
///
/// - `state`: Mutable reference to the deflate compression state. The
///   function reads from and writes to `window`, `strstart`, `lookahead`,
///   `match_length`, `sym_next`, `insert`, and `block_start`.
/// - `flush`: Flush mode from the caller. `Z_NO_FLUSH` allows the
///   function to return early when more input is needed. `Z_FINISH`
///   causes the final block to be emitted after the loop.
///
/// # Returns
///
/// - [`BlockState::NeedMore`] — Lookahead is insufficient and
///   `flush == Z_NO_FLUSH`; the caller should provide more input.
/// - [`BlockState::BlockDone`] — A non-final block was flushed.
/// - [`BlockState::FinishDone`] — The final block was emitted
///   (`flush == Z_FINISH`).
///
/// # C Source
///
/// Direct port of `deflate_rle` in `deflate.c:2084–2149`.
pub(crate) fn deflate_rle(state: &mut DeflateState, strm: *mut ZStream, flush: i32) -> BlockState {
    loop {
        // ------------------------------------------------------------------
        // Ensure sufficient lookahead.
        //
        // The RLE strategy needs up to MAX_MATCH (258) bytes of lookahead
        // for the longest possible run, plus one extra byte for the
        // unrolled initial comparison. Unlike the general strategies that
        // use MIN_LOOKAHEAD (262), RLE uses MAX_MATCH as its threshold
        // because it does not need the extra bytes for hash insertion.
        // ------------------------------------------------------------------
        if state.lookahead <= MAX_MATCH {
            // SAFETY: strm is valid for the duration of deflate().
            unsafe {
                do_fill_window(state, strm);
            }

            if state.lookahead <= MAX_MATCH && flush == Z_NO_FLUSH {
                return BlockState::NeedMore;
            }

            if state.lookahead == 0 {
                break; // Flush the current block
            }
        }

        // ------------------------------------------------------------------
        // Detect runs: see how many times the previous byte repeats.
        //
        // We look at window[strstart - 1] (the "previous" byte) and check
        // how many consecutive bytes starting at window[strstart] are
        // identical to it. A match at distance 1 with length >= MIN_MATCH
        // is emitted as a distance/length pair.
        //
        // The guard `strstart > 0` ensures we don't read before the
        // window start. At position 0, there is no "previous byte" to
        // match against, so only a literal can be emitted.
        // ------------------------------------------------------------------
        state.match_length = 0;

        if state.lookahead >= MIN_MATCH && state.strstart > 0 {
            // Byte at distance 1 from current position
            let prev = state.window[state.strstart - 1];

            // Quick check: first 3 bytes must match (minimum match length)
            if prev == state.window[state.strstart]
                && prev == state.window[state.strstart + 1]
                && prev == state.window[state.strstart + 2]
            {
                // At least MIN_MATCH bytes match. Scan forward to find the
                // full run length. The end boundary is strstart + MAX_MATCH,
                // clamped to the window size for safety.
                let scan_end = (state.strstart + MAX_MATCH).min(state.window.len());
                let mut pos = state.strstart + 3; // Already verified 3 bytes

                while pos < scan_end && state.window[pos] == prev {
                    pos += 1;
                }

                // Run length is the number of matching bytes from strstart
                state.match_length = pos - state.strstart;

                // Clamp to available lookahead
                if state.match_length > state.lookahead {
                    state.match_length = state.lookahead;
                }
            }
        }

        // ------------------------------------------------------------------
        // Emit match (distance 1) or literal
        // ------------------------------------------------------------------
        let bflush = if state.match_length >= MIN_MATCH {
            // Emit a distance/length pair. Distance is always 1 (RLE).
            // Length is encoded as (match_length - MIN_MATCH) per DEFLATE.
            let len = (state.match_length - MIN_MATCH) as u32;
            let result = tally_dist(state, 1, len);

            state.lookahead -= state.match_length;
            state.strstart += state.match_length;
            state.match_length = 0;

            result
        } else {
            // No run detected (or run too short). Emit a literal byte.
            let c = state.window[state.strstart];
            let result = tally_lit(state, c);

            state.lookahead -= 1;
            state.strstart += 1;

            result
        };

        // If the symbol buffer is full, flush the current block.
        if bflush {
            flush_block(state, false);
        }
    }

    // ------------------------------------------------------------------
    // Post-loop: finalize the block
    //
    // Set insert = 0 because the RLE strategy does not maintain the hash
    // table. If deflateParams later switches to a hash-based strategy,
    // the hash table will be rebuilt from scratch.
    // ------------------------------------------------------------------
    state.insert = 0;

    if flush == Z_FINISH {
        // Emit the final block (last = true).
        flush_block(state, true);
        return BlockState::FinishDone;
    }

    // If there are any pending symbols, flush a non-final block.
    if state.sym_next > 0 {
        flush_block(state, false);
    }

    BlockState::BlockDone
}

