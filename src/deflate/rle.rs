#![allow(dead_code)]

//! Run-length encoding (RLE) compression strategy for the DEFLATE engine.
//!
//! This module implements `deflate_rle`, one of five compression strategy
//! functions dispatched by the main `deflate()` loop. It is selected when
//! the caller specifies `Z_RLE` (strategy 3) via `deflateInit2` or
//! `deflateParams`.
//!
//! # Algorithm Overview
//!
//! Unlike the general LZ77 strategies (`deflate_fast`, `deflate_slow`),
//! `deflate_rle` only searches for runs of identical bytes at distance 1.
//! It does **not** maintain a hash table — hash chains are unused and the
//! `insert` counter is zeroed on exit. If the strategy is later changed
//! away from Z_RLE via `deflateParams`, the hash table will be
//! regenerated by the new strategy.
//!
//! # Wire-Format Compatibility
//!
//! The output is a valid DEFLATE stream (RFC 1951). Matches always have
//! distance = 1, so only the lowest distance code (code 0, extra bits = 0)
//! is used. This produces highly compressible output for data with many
//! repeated bytes, at the cost of very poor compression for non-repetitive
//! data.
//!
//! # C Source Reference
//!
//! - **Function:** `deflate_rle` in `deflate.c` lines 2084–2149
//! - **Called by:** Main `deflate()` loop when `state.strategy == Z_RLE`
//! - **Calls:** `fill_window`, `tally_dist`, `tally_lit`, `tr_flush_block`

