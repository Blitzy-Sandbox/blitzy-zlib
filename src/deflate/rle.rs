#[cfg(test)]
mod tests {
    use super::*;
    use crate::stream::ZStream;

    fn dummy_strm() -> ZStream {
        ZStream::new()
    }

    /// Helper: create a minimal `DeflateState` for testing the RLE
    /// algorithm. Sets up a small window with controlled data and
    /// configures the state so that the compression loop can run
    /// without needing the full deflate infrastructure.
    fn make_test_state(window_data: &[u8], strstart: usize, lookahead: usize) -> DeflateState {
        use crate::constants::Z_RLE;
        use crate::deflate::trees::tr_init;

        // Use minimal window/memory configuration
        let w_bits: usize = 9; // 512-byte window
        let mem_level: usize = 1;
        let level: usize = 1;
        let wrap: i32 = 0; // raw deflate

        let mut state = DeflateState::new(w_bits, mem_level, level, Z_RLE, wrap);

        // Initialize tree structures (descriptors, frequencies, block state).
        // This is essential — without tr_init, the tree flush operations
        // (build_tree/gen_bitlen) will panic on uninitialised descriptors.
        tr_init(&mut state);

        // Copy test data into the window
        let copy_len = window_data.len().min(state.window.len());
        state.window[..copy_len].copy_from_slice(&window_data[..copy_len]);

        // Set up the starting position and lookahead
        state.strstart = strstart;
        state.lookahead = lookahead;
        state.block_start = 0;
        state.window_size = state.window.len();
        state.match_length = 0;
        state.insert = 0;
        state.strategy = Z_RLE;

        state
    }

    #[test]
    fn test_rle_all_same_bytes() {
        // Window filled with all 'A' bytes. Starting at position 1
        // (so there's a "previous byte" at position 0), with enough
        // lookahead for a run.
        let data = vec![b'A'; 300];
        let mut state = make_test_state(&data, 1, 280);

        // Run with Z_FINISH to process all data
        let result = deflate_rle(&mut state, &mut dummy_strm() as *mut ZStream, Z_FINISH);

        // The function should process data and return FinishDone
        assert_eq!(result, BlockState::FinishDone);

        // insert should be 0 (no hash table maintained)
        assert_eq!(state.insert, 0);

        // strstart should have advanced past all the data
        assert!(state.strstart > 1);
    }

    #[test]
    fn test_rle_no_runs() {
        // Window filled with alternating bytes (no runs of length >= 3)
        let mut data = vec![0u8; 300];
        for (i, b) in data.iter_mut().enumerate() {
            *b = (i % 2) as u8;
        }
        let mut state = make_test_state(&data, 1, 200);

        let result = deflate_rle(&mut state, &mut dummy_strm() as *mut ZStream, Z_FINISH);

        assert_eq!(result, BlockState::FinishDone);
        assert_eq!(state.insert, 0);
    }

    #[test]
    fn test_rle_need_more_on_no_flush() {
        // With insufficient lookahead and Z_NO_FLUSH, should return NeedMore
        let data = vec![b'B'; 300];
        let mut state = make_test_state(&data, 1, 10); // Small lookahead <= MAX_MATCH

        let result = deflate_rle(&mut state, &mut dummy_strm() as *mut ZStream, Z_NO_FLUSH);

        assert_eq!(result, BlockState::NeedMore);
    }

    #[test]
    fn test_rle_strstart_zero_edge_case() {
        // At strstart == 0, there is no previous byte, so only literals
        // should be emitted.
        let data = vec![b'C'; 300];
        let mut state = make_test_state(&data, 0, 100);

        let result = deflate_rle(&mut state, &mut dummy_strm() as *mut ZStream, Z_FINISH);

        assert_eq!(result, BlockState::FinishDone);
        assert_eq!(state.insert, 0);
    }

    #[test]
    fn test_rle_mixed_runs_and_literals() {
        // Data with some runs and some non-repeating bytes
        let mut data = vec![0u8; 300];
        // Bytes 0-9: all 'A' (run of 10)
        for b in data.iter_mut().take(10) {
            *b = b'A';
        }
        // Bytes 10-14: different bytes (no run)
        data[10] = b'B';
        data[11] = b'C';
        data[12] = b'D';
        data[13] = b'E';
        data[14] = b'F';
        // Bytes 15-24: all 'X' (run of 10)
        for b in data.iter_mut().take(25).skip(15) {
            *b = b'X';
        }

        let mut state = make_test_state(&data, 1, 24);

        let result = deflate_rle(&mut state, &mut dummy_strm() as *mut ZStream, Z_FINISH);

        assert_eq!(result, BlockState::FinishDone);
        assert_eq!(state.insert, 0);
    }

    #[test]
    fn test_rle_empty_lookahead_with_finish() {
        // Zero lookahead with Z_FINISH should emit final block and return
        let data = vec![0u8; 300];
        let mut state = make_test_state(&data, 100, 0);

        let result = deflate_rle(&mut state, &mut dummy_strm() as *mut ZStream, Z_FINISH);

        assert_eq!(result, BlockState::FinishDone);
        assert_eq!(state.insert, 0);
    }

    #[test]
    fn test_rle_short_run_below_min_match() {
        // Run of exactly 2 bytes (below MIN_MATCH=3): should emit literals
        let mut data = vec![0u8; 300];
        data[0] = b'Z';
        data[1] = b'Z';
        data[2] = b'Z'; // 3 identical
        data[3] = b'Y'; // different

        let mut state = make_test_state(&data, 1, 10);

        // The run is exactly 3 bytes (MIN_MATCH), so should be emitted
        // as a match at distance 1.
        let result = deflate_rle(&mut state, &mut dummy_strm() as *mut ZStream, Z_FINISH);

        assert_eq!(result, BlockState::FinishDone);
    }

    #[test]
    fn test_rle_match_length_clamped_to_lookahead() {
        // Long run but limited lookahead: match_length should be clamped
        let data = vec![b'Q'; 300];
        let mut state = make_test_state(&data, 1, 5); // Only 5 bytes of lookahead

        // With Z_FINISH and limited lookahead, the run will be clamped
        let result = deflate_rle(&mut state, &mut dummy_strm() as *mut ZStream, Z_FINISH);

        assert_eq!(result, BlockState::FinishDone);
        assert_eq!(state.insert, 0);
    }
}
