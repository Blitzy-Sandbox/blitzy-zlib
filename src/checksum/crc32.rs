/// Update a running CRC-32 checksum with the bytes of `buf`.
///
/// This is the core public routine (the C `crc32_z`, whose length argument is a
/// `z_size_t`). `crc` is the previous checksum value — use `0` to start a fresh
/// computation — and the returned value is the updated checksum. The result is
/// bit-for-bit identical to C zlib regardless of how the input is chunked, so
/// streaming the data in pieces yields the same value as a single call.
///
/// Dispatch is resolved at compile time by the `simd` feature: with `simd` on
/// (the default) it uses the accelerated [`crc32fast`] backend, otherwise the
/// portable slice-by-8 `crc32_scalar`. An empty `buf` returns `crc` unchanged,
/// so `crc32_z(0, b"") == 0`. (C returns `0` for a `Z_NULL` buffer; that
/// pointer-specific fast path is handled at the FFI boundary in `ffi.rs`.)
///
/// # Examples
///
/// ```
/// use zlib_rs::checksum::crc32::crc32_z;
///
/// // Feeding the data in two pieces yields the same result as one shot.
/// let one_shot = crc32_z(0, b"abcdefgh");
/// let piece = crc32_z(0, b"abcd");
/// let split = crc32_z(piece, b"efgh");
/// assert_eq!(one_shot, split);
/// ```
pub fn crc32_z(crc: u32, buf: &[u8]) -> u32 {
    // Exactly one of these `return`s is compiled, so there is no unreachable
    // code and the dispatch is a zero-cost compile-time choice.
    #[cfg(feature = "simd")]
    return crc32_simd(crc, buf);
    #[cfg(not(feature = "simd"))]
    return crc32_scalar(crc, buf);
}

/// Update a running CRC-32 checksum with the bytes of `buf`.
///
/// Equivalent to [`crc32_z`]; provided to mirror the C public API where
/// `crc32` (with a 32-bit length) delegates to `crc32_z` (with a `size_t`
/// length). Seed `crc` with `0` to start a fresh checksum.
///
/// # Examples
///
/// ```
/// use zlib_rs::checksum::crc32::crc32;
///
/// assert_eq!(crc32(0, b""), 0);
/// assert_eq!(crc32(0, b"123456789"), 0xCBF4_3926);
/// ```
#[inline]
pub fn crc32(crc: u32, buf: &[u8]) -> u32 {
    crc32_z(crc, buf)
}

// ===========================================================================
// GF(2) polynomial arithmetic for combining CRCs
// ===========================================================================
//
// A CRC-32 is the remainder of the message polynomial divided by the CRC
// polynomial p(x), all computed in GF(2) (coefficients mod 2). To splice the
// CRC of `b` onto the CRC of `a` (forming the CRC of `a ++ b`) without
// rescanning `a`, the CRC of `a` must be advanced by `len(b)` zero bytes, which
// is a multiplication by `x^(8*len(b)) mod p(x)`. The helpers below implement
// that polynomial multiplication and the table of repeated-squaring powers that
// makes the advance run in O(log len) multiplies.

/// Multiply two polynomials modulo `p(x)` (the reflected CRC polynomial).
///
/// Operates on the reflected (LSB-first) bit representation used throughout
/// zlib. For speed — and to match the C reference exactly — this requires that
/// `a` not be zero; the loop terminates as soon as the highest remaining set bit
/// of `a` has been consumed. A zero `a` would loop forever, so every caller
/// guards against it (see [`crc32_combine_op`], which returns early when its
/// `op` is zero).
///
/// Declared `const fn` so it can build the compile-time [`X2N_TABLE`].
const fn multmodp(a: u32, b: u32) -> u32 {
    let mut m: u32 = 1u32 << 31;
    let mut p: u32 = 0;
    let mut b = b;
    loop {
        if a & m != 0 {
            p ^= b;
            if a & (m - 1) == 0 {
                return p;
            }
        }
        m >>= 1;
        b = if b & 1 != 0 { (b >> 1) ^ POLY } else { b >> 1 };
    }
}

/// Build the table of `x^(2^n) mod p(x)` for `n = 0..32`.
///
/// `X2N_TABLE[0]` is `x^1` (the reflected representation `1 << 30`), and each
/// subsequent entry squares the previous one via [`multmodp`], so
/// `X2N_TABLE[n] == x^(2^n) mod p(x)`. Mirrors the `x2n_table` initialization in
/// `crc32.c::make_crc_table()`. Evaluated at compile time.
const fn build_x2n_table() -> [u32; 32] {
    let mut t = [0u32; 32];
    t[0] = 1u32 << 30; // x^1
    let mut n = 1;
    while n < 32 {
        t[n] = multmodp(t[n - 1], t[n - 1]);
        n += 1;
    }
    t
}

/// `X2N_TABLE[n] = x^(2^n) mod p(x)`; the powers used to advance a CRC over a
/// run of zero bytes when combining. Built once at compile time.
const X2N_TABLE: [u32; 32] = build_x2n_table();

/// Return `x^(8*n) mod p(x)`, i.e. the polynomial that advances a CRC over `n`
/// zero bytes, where the byte count `n` is consumed starting at table index `k`.
///
/// Walks the bits of `n`, folding in `X2N_TABLE[k & 31]` (the next power of two)
/// for each set bit, exactly as `crc32.c::x2nmodp()` does. Seeds the accumulator
/// with `x^0 == 1` (the reflected representation `1 << 31`). Callers pass `k = 3`
/// to convert a *byte* length into the bit-length exponent (`8 = 2^3`).
fn x2nmodp(mut n: u64, mut k: u32) -> u32 {
    let mut p: u32 = 1u32 << 31; // x^0 == 1
    while n != 0 {
        if n & 1 != 0 {
            p = multmodp(X2N_TABLE[(k & 31) as usize], p);
        }
        n >>= 1;
        k += 1;
    }
    p
}

