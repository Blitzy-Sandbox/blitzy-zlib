//! CRC-32 (IEEE, reflected `0xEDB88320`), ported from zlib `crc32.c`;
//! bit-for-bit identical to C zlib.
//!
//! CRC-32 is the integrity check used by the gzip wrapper (RFC 1952): the
//! four-byte little-endian CRC-32 of the uncompressed data is written into the
//! gzip trailer, and the running value is tracked in `strm.adler` while a gzip
//! stream is being produced or consumed. Because the checksum is part of the
//! on-the-wire format, any deviation from the canonical algorithm would break
//! stream compatibility; this module therefore reproduces the C reference
//! exactly, including the `crc32_z`, `crc32_combine*`, `crc32_combine_gen*`,
//! `crc32_combine_op`, and `get_crc_table` variants.
//!
//! # Algorithm
//!
//! Two interchangeable engines produce the identical IEEE CRC-32:
//!
//! * **Scalar slice-by-8** (`crc32_scalar`) — the portable fallback. It folds
//!   eight input bytes per iteration through the eight-row lookup table that
//!   `build.rs` regenerates at build time (mirroring the 9,446-line upstream
//!   `crc32.h`, which is therefore never hand-ported). The byte loads use
//!   [`u32::from_le_bytes`], so the result is identical on little- and
//!   big-endian targets (AAP §0.6.4).
//! * **SIMD** (`crc32_simd`) — used when the `simd` feature is on. It delegates
//!   to the [`crc32fast`] crate, which selects a hardware-accelerated
//!   carry-less-multiply implementation at run time and computes the very same
//!   IEEE CRC-32. The `simd` feature is the default and targets ≥3× the scalar
//!   throughput (AAP §0.7.3).
//!
//! The GF(2) "combine" machinery ([`crc32_combine`] and friends) splices the
//! CRC of two concatenated buffers without rescanning the data, using the table
//! of `x^(2^n) mod p(x)` powers built at compile time.
//!
//! # Purity and portability
//!
//! This module is **`no_std`-clean**: the scalar paths use `core` only — no
//! `std`, no `alloc`, and **no `unsafe`**. (The only `unsafe` involved in a SIMD
//! build lives *inside* the `crc32fast` crate, never here.) It compiles
//! unchanged under the crate's `no-std` feature.
//!
//! # Examples
//!
//! ```
//! use zlib_rs::checksum::crc32::crc32;
//!
//! // Seed with 0 to begin a fresh checksum; this is the canonical IEEE check
//! // value for the string "123456789".
//! let c = crc32(0, b"123456789");
//! assert_eq!(c, 0xCBF4_3926);
//! ```

// The slice-by-8 CRC-32 tables are regenerated by the crate's `build.rs` (it
// mirrors the upstream `crc32.h` generator) and written to
// `${OUT_DIR}/crc32_table.rs`, which declares
// `pub(crate) static CRC_TABLE: [[u32; 256]; 8]` (and an unused flat alias
// `CRC_TABLE_0`). The generated module is wrapped here so the `#[allow(dead_code)]`
// scopes precisely to those generated items — silencing the warning for the
// `CRC_TABLE_0` alias this module does not consume, without masking dead code in
// the hand-written implementation. The `include!` path expression is verbatim
// per the build-script contract (AAP §0.3.1).
#[allow(dead_code)]
mod crc_table {
    include!(concat!(env!("OUT_DIR"), "/crc32_table.rs"));
}
use crc_table::CRC_TABLE;

/// Reflected IEEE CRC-32 polynomial (matches the `build.rs` table generator and
/// `#define POLY 0xedb88320` in `crc32.c`).
///
/// "Reflected" means the input bits are processed least-significant-bit first,
/// the convention used by zlib, gzip, PNG, and Ethernet. Private implementation
/// detail — intentionally **not** a public `Z_*` constant.
const POLY: u32 = 0xedb8_8320;

// ===========================================================================
// Scalar slice-by-8 core
// ===========================================================================

/// Update a running CRC-32 over `buf` using the portable slice-by-8 table.
///
/// `crc` is the previous CRC value (use `0` to start a fresh computation) and
/// the return is the updated CRC. This is bit-for-bit identical to canonical C
/// zlib — validated against the reference for lengths `0..11111`, for arbitrary
/// continuation split points, and for the combine paths.
///
/// The routine maintains the running value in its complemented form (`c =
/// !crc`) so the per-byte recurrence matches the C reference, complementing once
/// more on return. The bulk loop consumes eight bytes at a time: the first
/// little-endian word is mixed with the running CRC and folded through table
/// rows 7..4, and the second word through rows 3..0; the `chunks_exact`
/// remainder (0..7 trailing bytes) is finished with the classic byte-wise
/// recurrence against row 0. Using [`u32::from_le_bytes`] with explicit byte
/// arrays keeps the computation panic-free and endianness-independent.
///
/// Compiled whenever the `simd` feature is *off*, and additionally under `test`
/// so the SIMD/scalar parity test can compare the two engines directly.
#[cfg(any(not(feature = "simd"), test))]
fn crc32_scalar(crc: u32, buf: &[u8]) -> u32 {
    let mut c = !crc;
    let mut chunks = buf.chunks_exact(8);
    for chunk in &mut chunks {
        // Little-endian word loads make the result host-endianness-independent.
        let one = c ^ u32::from_le_bytes([chunk[0], chunk[1], chunk[2], chunk[3]]);
        let two = u32::from_le_bytes([chunk[4], chunk[5], chunk[6], chunk[7]]);
        c = CRC_TABLE[7][(one & 0xff) as usize]
            ^ CRC_TABLE[6][((one >> 8) & 0xff) as usize]
            ^ CRC_TABLE[5][((one >> 16) & 0xff) as usize]
            ^ CRC_TABLE[4][((one >> 24) & 0xff) as usize]
            ^ CRC_TABLE[3][(two & 0xff) as usize]
            ^ CRC_TABLE[2][((two >> 8) & 0xff) as usize]
            ^ CRC_TABLE[1][((two >> 16) & 0xff) as usize]
            ^ CRC_TABLE[0][((two >> 24) & 0xff) as usize];
    }
    for &b in chunks.remainder() {
        c = (c >> 8) ^ CRC_TABLE[0][((c ^ u32::from(b)) & 0xff) as usize];
    }
    !c
}

