/// Generate the combine operator for a second buffer of length `len2` (64-bit
/// length variant).
///
/// The returned "operator" is `x^(8*len2) mod p(x)`; pass it to
/// [`crc32_combine_op`] together with the two CRCs to splice them. Generating
/// the operator once and reusing it across many identically sized combines (the
/// purpose this split serves in the C API) avoids recomputing the power each
/// time. A negative `len2` is invalid and returns `0`, matching C zlib.
///
/// # Examples
///
/// ```
/// use zlib_rs::checksum::crc32::{crc32, crc32_combine_gen64, crc32_combine_op};
///
/// let a = b"Hello, ";
/// let b = b"world!";
/// let op = crc32_combine_gen64(b.len() as i64);
/// let combined = crc32_combine_op(crc32(0, a), crc32(0, b), op);
/// assert_eq!(combined, crc32(0, b"Hello, world!"));
/// ```
pub fn crc32_combine_gen64(len2: i64) -> u32 {
    if len2 < 0 { 0 } else { x2nmodp(len2 as u64, 3) }
}

/// Generate the combine operator for a second buffer of length `len2` (32-bit
/// length variant).
///
/// Identical in behavior to [`crc32_combine_gen64`]; both share one
/// implementation because Rust's `i64` length already covers the range the C
/// API splits across `z_off_t` and `z_off64_t`.
///
/// # Examples
///
/// ```
/// use zlib_rs::checksum::crc32::{crc32_combine_gen, crc32_combine_gen64};
///
/// assert_eq!(crc32_combine_gen(42), crc32_combine_gen64(42));
/// ```
#[inline]
pub fn crc32_combine_gen(len2: i64) -> u32 {
    crc32_combine_gen64(len2)
}

/// Combine two CRC-32 checksums using a precomputed operator from
/// [`crc32_combine_gen`] / [`crc32_combine_gen64`].
///
/// Computes `multmodp(op, crc1) ^ crc2`, which is the CRC of the first buffer
/// (advanced over the length of the second by `op`) spliced with the CRC of the
/// second buffer. Returns `crc2` blended over an advanced `crc1`, i.e. the CRC
/// of the two buffers concatenated.
///
/// A zero `op` returns `0`. Operators produced by the `*_combine_gen*` functions
/// for a valid (non-negative) length are always nonzero — `x^(8*len2) mod p(x)`
/// can never be the zero polynomial because `x` and `p(x)` are coprime (the CRC
/// polynomial has a nonzero constant term) — so this guard is a no-op for correct
/// inputs. It exists only to keep `multmodp` (which requires a nonzero first
/// argument) from looping forever if misused; the C reference is undefined/hangs
/// for `op == 0`.
///
/// # Examples
///
/// ```
/// use zlib_rs::checksum::crc32::{crc32, crc32_combine_gen, crc32_combine_op};
///
/// let a = b"foo";
/// let b = b"bar";
/// let op = crc32_combine_gen(b.len() as i64);
/// assert_eq!(
///     crc32_combine_op(crc32(0, a), crc32(0, b), op),
///     crc32(0, b"foobar")
/// );
/// ```
pub fn crc32_combine_op(crc1: u32, crc2: u32, op: u32) -> u32 {
    if op == 0 {
        return 0;
    }
    multmodp(op, crc1) ^ crc2
}

/// Combine two CRC-32 checksums into one, as if the second buffer had been
/// appended to the first (64-bit length variant).
///
/// Given `crc1 = crc32(0, a)` and `crc2 = crc32(0, b)` where `b` has length
/// `len2`, this returns `crc32(0, [a, b].concat())` without rescanning the data.
/// A negative `len2` produces the value for `op == 0` (`0`). Equivalent to
/// generating the operator with [`crc32_combine_gen64`] and applying it with
/// [`crc32_combine_op`].
///
/// # Examples
///
/// ```
/// use zlib_rs::checksum::crc32::{crc32, crc32_combine64};
///
/// let left = crc32(0, b"foo");
/// let right = crc32(0, b"bar");
/// assert_eq!(crc32_combine64(left, right, 3), crc32(0, b"foobar"));
/// ```
pub fn crc32_combine64(crc1: u32, crc2: u32, len2: i64) -> u32 {
    crc32_combine_op(crc1, crc2, crc32_combine_gen64(len2))
}

/// Combine two CRC-32 checksums into one (32-bit length variant).
///
/// Identical in behavior to [`crc32_combine64`]; both delegate to the same
/// machinery because Rust's `i64` length spans the 64-bit range the C API splits
/// across `z_off_t` and `z_off64_t`. `crc1` is the checksum of the first buffer,
/// `crc2` the checksum of the second, and `len2` the length (in bytes) of the
/// second buffer.
///
/// # Examples
///
/// ```
/// use zlib_rs::checksum::crc32::{crc32, crc32_combine};
///
/// let left = crc32(0, b"Hello, ");
/// let right = crc32(0, b"world!");
/// let whole = crc32(0, b"Hello, world!");
/// assert_eq!(crc32_combine(left, right, b"world!".len() as i64), whole);
/// ```
#[inline]
pub fn crc32_combine(crc1: u32, crc2: u32, len2: i64) -> u32 {
    crc32_combine64(crc1, crc2, len2)
}

