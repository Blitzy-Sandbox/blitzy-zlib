/// Update a running CRC-32 over `buf` using the SIMD-accelerated `crc32fast`
/// backend.
///
/// `crc32fast` computes the identical IEEE CRC-32 as zlib; seeding the hasher
/// with [`crc32fast::Hasher::new_with_initial`] continues from a previously
/// computed value, exactly matching C `crc32(crc, buf)`. The crate selects a
/// hardware carry-less-multiply path (e.g. SSE4.2/PCLMULQDQ or the AArch64 CRC
/// instructions) when available and falls back to a fast table method
/// otherwise — all `unsafe` is encapsulated inside `crc32fast`, never here.
///
/// Only compiled under the `simd` feature.
#[cfg(feature = "simd")]
#[inline]
fn crc32_simd(crc: u32, buf: &[u8]) -> u32 {
    let mut hasher = crc32fast::Hasher::new_with_initial(crc);
    hasher.update(buf);
    hasher.finalize()
}

